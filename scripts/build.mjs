/**
 * Build the browser half into the single module the Client module loader
 * expects: a `window.__ModuleLoader__.load({ id, factory })` registration whose
 * factory runs a self-contained CommonJS bundle and resolves React against the
 * page's shared module table.
 */
import { build } from 'esbuild'
import { cp, mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = dirname(here)
const manifest = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))
const packageName = manifest.name
const excalidrawDir = join(root, 'node_modules', '@excalidraw', 'excalidraw', 'dist', 'prod')

/** Point the bare package specifier at the production build, including its stylesheet. */
const excalidrawProd = {
  name: 'excalidraw-prod',
  setup(build) {
    build.onResolve({ filter: /^@excalidraw\/excalidraw(\/index\.css)?$/ }, (args) => ({
      path: args.path.endsWith('.css')
        ? join(excalidrawDir, 'index.css')
        : join(excalidrawDir, 'index.js'),
    }))
    // Mermaid, Cytoscape and KaTeX exist only for the paste-Mermaid dialog.
    build.onResolve({ filter: /^@excalidraw\/mermaid-to-excalidraw$/ }, () => ({
      path: join(root, 'src', 'client', 'stubs', 'mermaid.js'),
    }))
  },
}

const result = await build({
  entryPoints: [join(root, 'src', 'client', 'index.jsx')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome110', 'safari16', 'firefox115'],
  jsx: 'automatic',
  external: ['react', 'react-dom', 'react/jsx-runtime', 'react-dom/client'],
  loader: { '.css': 'text' },
  define: { 'process.env.NODE_ENV': '"production"' },
  minify: true,
  legalComments: 'none',
  logLevel: 'info',
  plugins: [excalidrawProd],
})

const body = result.outputFiles[0].text

const wrapped = `/* ${packageName} client bundle — generated by scripts/build.mjs, do not edit. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(packageName)},
  factory(require) {
    // Excalidraw fetches its handwriting fonts relative to this base; the Host
    // serves them from the package's own bundled assets.
    try {
      window.EXCALIDRAW_ASSET_PATH = new URL('plugins/${packageName}/', document.baseURI).href;
      var module = { exports: {} };
      var exports = module.exports;
      (function (module, exports, require) {
${body}
      })(module, exports, require);
      return module.exports;
    } catch (error) {
      // Report a module-initialisation failure to the Host: the page console is
      // the only other place it would show up.
      try {
        fetch('plugins/${packageName}/api/hello', {
          method: 'POST',
          headers: { 'content-type': 'application/json' },
          body: JSON.stringify({ stage: 'factory-failed', error: String((error && error.stack) || error) }),
        }).catch(function () {});
      } catch (ignored) {
        // Reporting must never mask the original failure.
      }
      throw error;
    }
  },
});
`

await mkdir(join(root, 'lib'), { recursive: true })
await writeFile(join(root, 'lib', 'client.js'), wrapped, 'utf8')

// Fonts travel with the package so the Host route has something to serve.
const fontSource = join(excalidrawDir, 'fonts')
const fontTarget = join(root, 'assets', 'fonts')
await rm(fontTarget, { recursive: true, force: true })
await mkdir(fontTarget, { recursive: true })
await cp(fontSource, fontTarget, { recursive: true })

const size = (await stat(join(root, 'lib', 'client.js'))).size
console.log(`client bundle: ${(size / 1024 / 1024).toFixed(2)} MiB -> lib/client.js`)
